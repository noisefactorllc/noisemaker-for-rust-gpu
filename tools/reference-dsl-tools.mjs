function defineOwn (obj, key, value) {
  Object.defineProperty(obj, key, { value, enumerable: true, writable: true, configurable: true })
}

let EffectClass = null

// The reference's Effect class, for tools that import this encoding without
// loadReference() (tools/reference-api.mjs).
export function useEffectClass (cls) {
  EffectClass = cls
}

function prototypeMethodNames (instance) {
  const names = []
  let proto = Object.getPrototypeOf(instance)
  while (proto && proto !== EffectClass.prototype && proto !== Object.prototype) {
    for (const key of Object.getOwnPropertyNames(proto)) {
      if (key !== 'constructor' && !names.includes(key)) names.push(key)
    }
    proto = Object.getPrototypeOf(proto)
  }
  return names
}

export function encode (value, depth = 0) {
  if (depth > 200) throw new Error('encode: value nests too deeply (cycle?)')
  if (value === undefined) return { [TAG]: 'undefined' }
  if (value === null || typeof value === 'boolean' || typeof value === 'string') return value
  if (typeof value === 'number') {
    if (Number.isNaN(value)) return { [TAG]: 'NaN' }
    if (value === Infinity) return { [TAG]: 'Infinity' }
    if (value === -Infinity) return { [TAG]: '-Infinity' }
    if (Object.is(value, -0)) return { [TAG]: '-0' }
    return value
  }
  if (typeof value === 'function') {
    if (EffectClass && value.prototype instanceof EffectClass) {
      const prototypeMethods = Object.getOwnPropertyNames(value.prototype).filter(k => k !== 'constructor')
      const statics = {}
      for (const key of Object.getOwnPropertyNames(value)) {
        defineOwn(statics, key, key === 'prototype' ? {} : encode(value[key], depth + 1))
      }
      return { [TAG]: 'effectSubclass', prototypeMethods, statics }
    }
    return { [TAG]: 'function', source: String(value) }
  }
  if (typeof value !== 'object') throw new Error(`encode: unsupported ${typeof value}`)
  if (ArrayBuffer.isView(value)) return { [TAG]: value.constructor.name, values: Array.from(value, v => encode(v, depth + 1)) }
  if (value instanceof Map) return { [TAG]: 'Map', entries: [...value].map(([k, v]) => [encode(k, depth + 1), encode(v, depth + 1)]) }
  if (value instanceof Error) return { [TAG]: 'error', name: value.name, message: value.message }
  if (Array.isArray(value)) return Array.from(value, v => encode(v, depth + 1))
  const members = {}
  for (const key of Object.keys(value)) defineOwn(members, key, encode(value[key], depth + 1))
  if (EffectClass && value instanceof EffectClass) {
    return { [TAG]: 'effectInstance', props: members, prototypeMethods: prototypeMethodNames(value) }
  }
  if (Object.hasOwn(members, TAG)) return { [TAG]: 'object', members }
  return members
}

function makeFunction (source) {
  const fn = (() => function () {})()
  Object.defineProperty(fn, 'toString', { value: () => source, enumerable: false })
  return fn
}

const ERROR_TYPES = { Error, SyntaxError, TypeError, RangeError, ReferenceError, EvalError, URIError }

export function decode (value) {
  if (value === null || typeof value !== 'object') return value
  if (Array.isArray(value)) return value.map(decode)
  if (Object.hasOwn(value, TAG)) {
    switch (value[TAG]) {
      case 'undefined': return undefined
      case 'NaN': return NaN
      case 'Infinity': return Infinity
      case '-Infinity': return -Infinity
      case '-0': return -0
      case 'function': return makeFunction(value.source)
      case 'Float32Array': return new Float32Array(value.values.map(decode))
      case 'Float64Array': return new Float64Array(value.values.map(decode))
      case 'Map': return new Map(value.entries.map(([k, v]) => [decode(k), decode(v)]))
      case 'object': return decodeMembers(value.members)
      case 'error': {
        const Ctor = ERROR_TYPES[value.name] || Error
        const err = new Ctor(value.message)
        if (!ERROR_TYPES[value.name]) err.name = value.name
        return err
      }
      case 'effectInstance': {
        // An Effect instance whose subclass prototype has the given methods.
        class Instance extends EffectClass {}
        for (const name of value.prototypeMethods || []) Instance.prototype[name] = function () {}
        const instance = Object.create(Instance.prototype)
        const props = decodeMembers(value.props)
        for (const key of Object.keys(props)) defineOwn(instance, key, props[key])
        return instance
      }
      case 'effectSubclass': {
        const statics = value.statics || {}
        const Sub = ({ [typeof statics.name === 'string' ? statics.name : 'Subclass']: class extends EffectClass {} })[typeof statics.name === 'string' ? statics.name : 'Subclass']
        for (const name of value.prototypeMethods || []) Sub.prototype[name] = function () {}
        for (const key of Object.keys(statics)) {
          if (key === 'prototype' || key === 'length' || key === 'name') continue
          Object.defineProperty(Sub, key, { value: decode(statics[key]), enumerable: true, writable: true, configurable: true })
        }
        return Sub
      }
      default: throw new Error(`decode: unknown tag ${value[TAG]}`)
    }
  }
  return decodeMembers(value)
}

function decodeMembers (obj) {
  const out = {}
  for (const key of Object.keys(obj)) defineOwn(out, key, decode(obj[key]))
  return out
}

