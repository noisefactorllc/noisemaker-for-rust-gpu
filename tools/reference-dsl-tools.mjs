async function loadReference () {
  const mod = await bootstrapReference()
  const unparser = await refModule('lang/unparser.js')
  const transform = await refModule('lang/transform.js')
  const errorFormatter = await refModule('lang/error-formatter.js')
  const effectValidator = await refModule('runtime/effect-validator.js')
  const effect = await refModule('runtime/effect.js')
  const opsModule = await refModule('lang/ops.js')
  const validator = await refModule('lang/validator.js')
  const registry = await refModule('runtime/registry.js')
  const paramAliases = await refModule('lang/paramAliases.js')
  const effectAliases = await refModule('lang/effectAliases.js')
  const enums = await refModule('lang/enums.js')
  const stdEnumsModule = await refModule('lang/std_enums.js')
  EffectClass = effect.Effect
  return {
    ...mod,
    ...unparser,
    ...transform,
    ...errorFormatter,
    ...effectValidator,
    Effect: effect.Effect,
    ops: opsModule.ops,
    registerOp: opsModule.registerOp,
    registerStarterOps: validator.registerStarterOps,
    isStarterOp: validator.isStarterOp,
    registerEffect: registry.registerEffect,
    getEffect: registry.getEffect,
    registerParamAliases: paramAliases.registerParamAliases,
    registerEffectAlias: effectAliases.registerEffectAlias,
    mergeIntoEnums: enums.mergeIntoEnums,
    enumsModule: enums,
    langStdEnums: stdEnumsModule.stdEnums,
    manifest: JSON.parse(readFileSync(join(EFFECTS, 'manifest.json'), 'utf8'))
  }
}

async function applySetup (m, setup) {
  for (const step of setup || []) {
    switch (step.op) {
      case 'registerOp': m.registerOp(step.name, decode(step.spec)); break
      case 'registerStarterOps': m.registerStarterOps(decode(step.names)); break
      case 'registerEffect': m.registerEffect(step.name, decode(step.definition)); break
      case 'registerParamAliases': m.registerParamAliases(step.opName, decode(step.aliases)); break
      case 'registerEffectAlias': m.registerEffectAlias(step.opName, step.newName); break
      case 'mergeIntoEnums': await m.mergeIntoEnums(decode(step.source)); break
      default: throw new Error(`unknown setup op ${step.op}`)
    }
  }
}

// deepMerge of lang/enums.js (the host merges the std enums first, then every
// effect's choice tables).
function deepMergeEnums (target, source) {
  for (const key of Object.keys(source)) {
    if (key === '__proto__' || key === 'constructor' || key === 'prototype') continue
    const s = source[key]
    const t = target[key]
    if (s && typeof s === 'object' && !Array.isArray(s) && t && typeof t === 'object' && !Array.isArray(t) && !('type' in s)) {
      deepMergeEnums(t, s)
    } else {
      target[key] = s && typeof s === 'object' ? structuredClone(s) : s
    }
  }
  return target
}

// "std": lang/std_enums.js; "host": the std enums merged with every registered
// choice table (the enum tree CanvasRenderer builds).
function enumsFor (m, name) {
  if (name === 'std') return m.langStdEnums
  if (name === 'host') {
    if (!m.hostEnums) {
      m.hostEnums = deepMergeEnums(deepMergeEnums({}, m.langStdEnums), m.enumsModule.default || {})
    }
    return m.hostEnums
  }
  throw new Error(`unknown enums source ${name}`)
}

