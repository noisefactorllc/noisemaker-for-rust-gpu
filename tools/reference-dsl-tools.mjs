const HOST_UNPARSE_OPTIONS = {
  getEffectDef: { kind: 'registry' },
  customFormatter: { kind: 'formatValue', enums: { $enums: 'host' } }
}

function fixtureFiles (dirs) {
  const files = []
  for (const dir of dirs) {
    for (const f of readdirSync(join(ROOT, dir)).filter(f => f.endsWith('.dsl')).sort()) {
      files.push({ dir, name: f.replace(/\.dsl$/, ''), path: join(ROOT, dir, f) })
    }
  }
  return files
}

// Deterministic parameter edits: the first numeric or boolean argument of the
// first two effect steps, plus a _skip on the first read step.
function generateUpdates (compiled) {
  const updates = {}
  let index = 0
  let picked = 0
  let skipped = false
  for (const plan of compiled.plans || []) {
    for (const step of plan.chain || []) {
      if (step.builtin && step.op === '_read' && !skipped) {
        updates[index] = { _skip: true }
        skipped = true
      } else if (!step.builtin && picked < 2) {
        for (const [key, value] of Object.entries(step.args || {})) {
          if (typeof value === 'number') {
            updates[index] = { [key]: Number.isInteger(value) ? value + 1 : value * 0.5 + 0.125 }
            picked++
            break
          }
          if (typeof value === 'boolean') {
            updates[index] = { [key]: !value }
            picked++
            break
          }
        }
      }
      index++
    }
  }
  return updates
}

function * generateFixtureCases (m, gen, resolver) {
  const every = gen.compatibleEvery || 0
  let n = 0
  for (const { dir, name, path } of fixtureFiles(gen.dirs)) {
    const src = readFileSync(path, 'utf8')
    const id = `${dir.replace(/^parity\//, '')}/${name}`
    let compiled
    try {
      compiled = resolver.compile(src)
    } catch {
      for (const contextLines of [undefined, 0, 1, 4]) {
        yield { id: `${id}#formatDslError${contextLines === undefined ? '' : `:${contextLines}`}`, op: 'formatDslError', source: src, error: { $errorOf: { $compile: src } }, ...(contextLines === undefined ? {} : { options: { contextLines } }) }
      }
      yield { id: `${id}#isDslSyntaxError`, op: 'isDslSyntaxError', error: { $errorOf: { $compile: src } } }
      continue
    }
    yield { id: `${id}#unparse`, op: 'unparse', compiled: { $compile: src } }
    yield { id: `${id}#unparse:host`, op: 'unparse', compiled: { $compile: src }, options: HOST_UNPARSE_OPTIONS }
    yield { id: `${id}#unparse:compact`, op: 'unparse', compiled: { $compile: src }, overrides: {}, options: { multilineKwargs: false, omitSearchDirective: true } }
    // Second round trip: unparse the reference's own regenerated program.
    let once
    try {
      once = m.unparse(compiled)
    } catch {
      once = null
    }
    if (typeof once === 'string') {
      let ok = true
      try { resolver.compile(once) } catch { ok = false }
      if (ok) {
        yield { id: `${id}#unparse2`, op: 'unparse', compiled: { $compile: once } }
      } else {
        yield { id: `${id}#unparse2:formatDslError`, op: 'formatDslError', source: once, error: { $errorOf: { $compile: once } } }
      }
    }
    yield { id: `${id}#steps`, op: 'listSteps', compiled: { $compile: src } }
    yield { id: `${id}#applyParameterUpdates`, op: 'applyParameterUpdates', dsl: src, updates: generateUpdates(compiled) }

    // Replacements: a starter at the first starter position, a filter at the
    // first non-starter position, and an illegal swap.
    let steps = []
    try { steps = m.listSteps(compiled) } catch {}
    const starter = steps.find(s => s.isStarterPosition)
    const filter = steps.find(s => !s.isStarterPosition)
    if (starter) {
      yield { id: `${id}#replace:solid`, op: 'replaceEffectUnparse', compiled: { $compile: src }, stepIndex: starter.stepIndex, newEffectName: 'solid', newArgs: { color: [0.25, 0.5, 0.75] } }
      yield { id: `${id}#replace:noise`, op: 'replaceEffect', compiled: { $compile: src }, stepIndex: starter.stepIndex, newEffectName: 'synth.noise', newArgs: { seed: 7, scaleX: 1.23456 }, options: { preflight: true } }
      yield { id: `${id}#replace:illegal-starter`, op: 'replaceEffect', compiled: { $compile: src }, stepIndex: starter.stepIndex, newEffectName: 'blur' }
    }
    if (filter) {
      yield { id: `${id}#replace:blur`, op: 'replaceEffectUnparse', compiled: { $compile: src }, stepIndex: filter.stepIndex, newEffectName: 'blur', newArgs: { radiusX: 3.14159 }, unparseOptions: HOST_UNPARSE_OPTIONS }
      yield { id: `${id}#replace:filter.grain`, op: 'replaceEffect', compiled: { $compile: src }, stepIndex: filter.stepIndex, newEffectName: 'grain', newArgs: { amount: 5, bogus: 1 } }
      yield { id: `${id}#replace:illegal-filter`, op: 'replaceEffect', compiled: { $compile: src }, stepIndex: filter.stepIndex, newEffectName: 'noise' }
    }
    if (every && (n++ % every === 0) && steps.length) {
      const target = steps[steps.length - 1]
      yield { id: `${id}#compatible`, op: 'getCompatibleReplacements', compiled: { $compile: src }, stepIndex: target.stepIndex, options: { preflight: n % 2 === 0, manifest: { $manifest: true } } }
    }
  }
}

function formatValueCases (m, gen, resolver) {
  const out = []
  for (const { dir, name, path } of fixtureFiles(gen.dirs)) {
    const src = readFileSync(path, 'utf8')
    const id = `${dir.replace(/^parity\//, '')}/${name}`
    let compiled
    try { compiled = resolver.compile(src) } catch { continue }
    compiled.plans.forEach((plan, p) => {
      (plan.chain || []).forEach((step, c) => {
        if (step.builtin) return
        for (const key of Object.keys(step.args || {})) {
          const value = { $compile: src, path: ['plans', p, 'chain', c, 'args', key] }
          const spec = { $effect: step.op, path: ['globals', key] }
          const base = `${id}#formatValue:${p}.${c}.${key}`
          out.push({ id: base, op: 'formatValue', value, spec, options: { enums: { $enums: 'host' } } })
          out.push({ id: `${base}:bare`, op: 'formatValue', value })
        }
      })
    })
  }
  return out
}

function catalogCases () {
  const out = []
  for (const namespace of readdirSync(EFFECTS, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
    for (const effect of readdirSync(join(EFFECTS, namespace), { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
      if (!existsSync(join(EFFECTS, namespace, effect, 'definition.js'))) continue
      const id = `${namespace}/${effect}`
      out.push({ id: `catalog/${id}#instance`, op: 'validateEffectDefinition', definition: { $catalogInstance: id } })
      out.push({ id: `catalog/${id}#json`, op: 'validateEffectDefinition', definition: { $catalogJson: id } })
    }
  }
  return out
}

function predictionCases (m) {
  const out = []
  for (const name of Object.keys(m.ops)) {
    out.push({ id: `predict/${name}`, op: 'predictReplacement', resolvedName: name, spec: { $op: name }, newArgs: {}, oldInstance: null, options: { manifest: { $manifest: true } } })
  }
  return out
}

async function expandCases (m, suite, resolver) {
  const out = []
  for (const entry of suite.cases || []) {
    if (!entry.generate) {
      out.push(entry)
      continue
    }
    switch (entry.generate) {
      case 'fixtures': for (const c of generateFixtureCases(m, entry, resolver)) out.push(c); break
      case 'formatValue': out.push(...formatValueCases(m, entry, resolver)); break
      case 'catalog': out.push(...catalogCases()); break
      case 'predictions': out.push(...predictionCases(m)); break
      default: throw new Error(`unknown generator ${entry.generate}`)
    }
  }
  return out
}

// ---------------------------------------------------------------------------
// Running cases
// ---------------------------------------------------------------------------

// The first `$compile` argument of a case whose program throws, if any.
async function compileFailure (resolver, c) {
  for (const value of Object.values(c)) {
    if (!value || typeof value !== 'object' || !('$compile' in value)) continue
    let src
    try { src = await resolver.eval(value.$compile) } catch { continue }
    try { resolver.compile(src, value.options) } catch { return { src, options: value.options } }
  }
  return null
}

function thrownRecord (error) {
  if (error instanceof Error) return { name: error.name, message: error.message }
  return { thrown: encode(error) }
}

function runOp (m, spec, args) {
  try {
    return { value: spec.run(m, args) }
  } catch (error) {
    return { error }
  }
}

function encodedOutcome (outcome) {
  return 'error' in outcome ? { error: thrownRecord(outcome.error) } : { result: encode(outcome.value) }
}

async function runCases (suitePath, resolvedPath, expectedPath, liveCheck) {
  const suite = JSON.parse(readFileSync(suitePath, 'utf8'))
  const m = await loadReference()
  await applySetup(m, suite.setup)
  const resolver = new Resolver(m)
  const cases = await expandCases(m, suite, resolver)
  const resolvedLines = [JSON.stringify({ setup: suite.setup || [], profile: suite.profile || basename(suitePath) })]
  const expectedLines = []
  const liveMismatches = []
  const ids = new Set()
  for (let index = 0; index < cases.length; index++) {
    const c = cases[index]
    const spec = OPS[c.op]
    if (!spec) throw new Error(`case ${c.id}: unknown op ${c.op}`)
    if (ids.has(c.id)) throw new Error(`duplicate case id ${c.id}`)
    ids.add(c.id)
    const category = c.category || spec.category
    // Evaluate the arguments with the reference.
    const live = {}
    const resolved = { id: c.id, op: c.op, category }
    try {
      for (const name of spec.args) {
        if (c.op === 'applyParameterUpdates' && (name === 'compiled' || name === 'compileError')) continue
        if (!(name in c)) continue
        live[name] = await resolver.eval(c[name])
        resolved[name] = encode(live[name])
        // Record the DSL behind a compiled argument (nm-dsl --rust-frontend
        // compiles it with the Rust frontend instead).
        const expr = c[name]
        if (expr && typeof expr === 'object' && '$compile' in expr && !expr.path && !expr.omit) {
          resolved.compiledFrom = resolved.compiledFrom || {}
          resolved.compiledFrom[name] = { dsl: await resolver.eval(expr.$compile), options: expr.options ?? null }
        }
      }
      if (c.op === 'applyParameterUpdates') {
        if ('compiled' in c || 'compileError' in c) {
          // A literal compile result (or thrown value) for the compile function.
          const literal = 'compiled' in c ? await resolver.eval(c.compiled) : undefined
          const thrown = 'compileError' in c ? await resolver.eval(c.compileError) : undefined
          if ('compiled' in c) resolved.compiled = encode(literal)
          else resolved.compileError = encode(thrown)
          resolved.compiledLiteral = true
          live.compileFn = () => {
            if ('compileError' in c) throw thrown
            return literal
          }
        } else {
          // applyParameterUpdates mutates the compile result: the live run gets
          // fresh compiles, the cache is only read.
          try {
            resolved.compiled = encode(resolver.compile(live.dsl))
          } catch (error) {
            resolved.compileError = encode(error)
          }
          live.compileFn = src => m.compile(src)
        }
      }
    } catch (error) {
      // A program that does not compile (a regenerated program the DSL cannot
      // read back) is checked through the error formatter instead.
      const failed = await compileFailure(resolver, c)
      if (!failed) throw new Error(`case ${c.id}: cannot evaluate arguments: ${error?.stack || error}`)
      cases.splice(cases.indexOf(c) + 1, 0, { id: `${c.id}:formatDslError`, op: 'formatDslError', source: failed.src, error: { $errorOf: { $compile: failed.src, ...(failed.options ? { options: failed.options } : {}) } } })
      continue
    }
    // Run on the decoded inputs (what nm-dsl sees).
    const decoded = {}
    for (const name of spec.args) if (name in resolved) decoded[name] = decode(resolved[name])
    const outcome = runOp(m, spec, decoded)
    resolver.results.set(c.id, outcome)
    const record = { id: c.id, category, ...encodedOutcome(outcome) }
    expectedLines.push(JSON.stringify(record))
    resolvedLines.push(JSON.stringify(resolved))
    if (liveCheck) {
      const liveOutcome = runOp(m, spec, live)
      const a = JSON.stringify(encodedOutcome(liveOutcome))
      const b = JSON.stringify(encodedOutcome(outcome))
      if (a !== b) liveMismatches.push({ id: c.id, live: a.slice(0, 400), decoded: b.slice(0, 400) })
    }
  }
  writeFileSync(resolvedPath, resolvedLines.join('\n') + '\n')
  writeFileSync(expectedPath, expectedLines.join('\n') + '\n')
  if (liveCheck) {
    for (const mm of liveMismatches) console.error(`[reference-dsl-tools] live/decoded difference in ${mm.id}:\n  live:    ${mm.live}\n  decoded: ${mm.decoded}`)
    process.stdout.write(JSON.stringify({ cases: cases.length, liveMismatches: liveMismatches.length }) + '\n')
  } else {
    process.stdout.write(JSON.stringify({ cases: cases.length }) + '\n')
  }
}

async function main () {
  const argv = process.argv.slice(2)
  const command = argv.shift()
  if (command === 'cases') {
    let suite = null; let resolved = null; let expected = null; let liveCheck = false
    for (let i = 0; i < argv.length; i++) {
      if (argv[i] === '--resolved') resolved = argv[++i]
      else if (argv[i] === '--expected') expected = argv[++i]
      else if (argv[i] === '--live-check') liveCheck = true
      else suite = argv[i]
    }
    if (!suite || !resolved || !expected) throw new Error('usage: cases <suite.json> --resolved R --expected E [--live-check]')
    await runCases(suite, resolved, expected, liveCheck)
    return
  }
  const m = await loadReference()
  if (command === 'unparse') {
    process.stdout.write(m.unparse(m.compile(readFileSync(argv[0], 'utf8'))) + '\n')
  } else if (command === 'steps') {
    process.stdout.write(JSON.stringify(encode(m.listSteps(m.compile(readFileSync(argv[0], 'utf8'))))) + '\n')
  } else if (command === 'validate') {
    process.stdout.write(JSON.stringify(m.validateEffectDefinition(await catalogInstance(argv[0]))) + '\n')
  } else {
    console.error('usage: node tools/reference-dsl-tools.mjs cases|unparse|steps|validate ...')
    process.exit(2)
  }
}

if (process.argv[1] && basename(process.argv[1]) === 'reference-dsl-tools.mjs') {
  main().catch(err => {
    console.error(`[reference-dsl-tools] FAILED: ${err?.stack || err}`)
    process.exit(1)
  })
}
