function catalogInstance (id) {
  return import(pathToFileURL(join(EFFECTS, id, 'definition.js')).href).then(mod => {
    const exported = mod.default
    return typeof exported === 'function' ? new exported() : exported
  })
}

function catalogJson (id) {
  return JSON.parse(readFileSync(join(CATALOG, id, 'definition.json'), 'utf8'))
}

function navigate (value, path) {
  let v = value
  for (const key of path || []) v = v?.[key]
  return v
}

class Resolver {
  constructor (m) {
    this.m = m
    this.results = new Map()
    this.compileCache = new Map()
  }

  compile (src, options) {
    const key = JSON.stringify([src, options ?? null])
    if (!this.compileCache.has(key)) {
      try {
        this.compileCache.set(key, { value: this.m.compile(src, options) })
      } catch (error) {
        this.compileCache.set(key, { error })
      }
    }
    const entry = this.compileCache.get(key)
    if ('error' in entry) throw entry.error
    return entry.value
  }

  // Evaluate a value expression to a live reference value.
  async eval (expr) {
    if (expr === null || typeof expr !== 'object') return expr
    if (Array.isArray(expr)) {
      const out = []
      for (const e of expr) out.push(await this.eval(e))
      return out
    }
    if (Object.hasOwn(expr, TAG)) return decode(await this.evalMembers(expr))
    const keys = Object.keys(expr)
    const op = keys.find(k => k.startsWith('$'))
    if (!op) return this.evalMembers(expr)
    let value
    switch (op) {
      case '$compile': value = this.compile(await this.eval(expr.$compile), expr.options); break
      case '$parse': value = this.m.parse(this.m.lex(await this.eval(expr.$parse))); break
      case '$file': value = readFileSync(join(ROOT, expr.$file), 'utf8'); break
      case '$resultOf': {
        if (!this.results.has(expr.$resultOf)) throw new Error(`no result for case ${expr.$resultOf}`)
        const r = this.results.get(expr.$resultOf)
        if ('error' in r) throw new Error(`case ${expr.$resultOf} threw`)
        value = r.value
        break
      }
      case '$errorOf': {
        let threw = false
        try {
          await this.eval(expr.$errorOf)
        } catch (error) {
          threw = true
          value = error
        }
        if (!threw) throw new Error(`$errorOf: expression did not throw: ${JSON.stringify(expr.$errorOf)}`)
        break
      }
      case '$op': value = this.m.ops[expr.$op]; break
      case '$effect': value = this.m.getEffect(expr.$effect); break
      case '$catalogInstance': value = await catalogInstance(expr.$catalogInstance); break
      case '$catalogJson': value = catalogJson(expr.$catalogJson); break
      case '$manifest': value = this.m.manifest; break
      case '$enums': return expr // interpreted by both tools
      case '$legacyFormatter': return expr
      default: throw new Error(`unknown expression ${op}`)
    }
    value = navigate(value, expr.path)
    if (expr.omit && value && typeof value === 'object') {
      const copy = { ...value }
      for (const key of expr.omit) delete copy[key]
      value = copy
    }
    return value
  }

  async evalMembers (obj) {
    const out = {}
    for (const key of Object.keys(obj)) defineOwn(out, key, await this.eval(obj[key]))
    return out
  }
}

