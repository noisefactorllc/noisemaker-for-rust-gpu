#!/usr/bin/env node
// reference-dsl-tools.mjs — run the unmodified reference DSL tooling (unparser,
// transform, error formatter, effect-definition validator) over a case suite.
//
// The reference engine at $NM_REFERENCE_ROOT is bootstrapped exactly like
// tools/reference-oracle.mjs does it (bootstrapReference: the host's
// registration of every catalog effect), which is the state
// noisemaker_dsl::Registry::with_catalog() reproduces.
//
// A case suite (parity/dsl-tools/*.json) is {profile, setup, cases}:
//   setup  registry mutations applied after the host registration (the
//          reference test files register mock ops, effects and aliases);
//   cases  [{id, op, ...arguments}]; arguments may be value expressions that
//          this tool evaluates with the reference (compile a DSL program, take
//          the error a program throws, read a catalog definition, ...);
//          {"generate": <name>, ...} entries expand to generated cases.
//
// `cases` writes two JSON-lines files:
//   --resolved  the cases with every argument evaluated and encoded (the input
//               nm-dsl runs), preceded by a {"setup": [...]} header line;
//   --expected  one {"id", "category", "result"} or {"id", "category", "error"}
//               record per case: the reference's output on those same inputs.
// Values use a tagged JSON encoding so that undefined, NaN, ±Infinity, -0,
// functions, typed arrays and Effect instances survive the round trip:
// {"$js": "undefined" | "NaN" | "Infinity" | "-Infinity" | "-0"},
// {"$js": "function", "source"}, {"$js": "Float32Array", "values"},
// {"$js": "Map", "entries"}, {"$js": "object", "members"} (an object with an own
// "$js" key), {"$js": "error", "name", "message"},
// {"$js": "effectInstance", "props", "prototypeMethods"},
// {"$js": "effectSubclass", "prototypeMethods", "statics"}.
//
// Every case runs on the decoded copy of its encoded arguments (the inputs
// nm-dsl sees). With --live-check the case also runs on the live values the
// reference produced, and any difference is reported (an input the encoding
// cannot carry).
//
// Usage:
//   node tools/reference-dsl-tools.mjs cases <suite.json> --resolved R --expected E [--live-check]
//   node tools/reference-dsl-tools.mjs unparse <program.dsl>      DSL regenerated by unparse()
//   node tools/reference-dsl-tools.mjs steps <program.dsl>        listSteps() as JSON
//   node tools/reference-dsl-tools.mjs validate <ns/effect>       validateEffectDefinition() of a catalog effect

