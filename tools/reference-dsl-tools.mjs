function effectDefCallback (m, spec) {
  switch (spec.kind) {
    case 'registry':
      // createEffectDefCallback(getEffect) (demo/shaders/lib/demo-ui.js), the
      // ProgramState.toDsl lookup.
      return (effectName, namespace) => {
        let def = m.getEffect(effectName)
        if (def) return def
        if (effectName.includes('.')) {
          def = m.getEffect(effectName.replace('.', '/'))
          if (def) return def
        }
        if (namespace) {
          def = m.getEffect(`${namespace}/${effectName}`) || m.getEffect(`${namespace}.${effectName}`)
          if (def) return def
        }
        return null
      }
    case 'registrySimple':
      // ProgramState.deleteStep / insertStep lookup.
      return (name, ns) => {
        let def = m.getEffect(name)
        if (!def && ns) def = m.getEffect(`${ns}/${name}`) || m.getEffect(`${ns}.${name}`)
        return def
      }
    case 'map': {
      const defs = spec.defs
      return name => (Object.hasOwn(defs, name) ? defs[name] : null)
    }
    case 'constant': {
      const def = spec.def
      return () => def
    }
    case 'ops':
      return name => m.ops[name] || null
    default: throw new Error(`unknown getEffectDef kind ${spec.kind}`)
  }
}

function enumsValue (m, v) {
  if (v && typeof v === 'object' && !Array.isArray(v) && typeof v.$enums === 'string') return enumsFor(m, v.$enums)
  return v
}

function customFormatterFn (m, spec) {
  if (spec.kind === 'formatValue') {
    const enums = enumsValue(m, spec.enums)
    return (value, s) => m.formatValue(value, s, { enums })
  }
  throw new Error(`unknown customFormatter kind ${spec.kind}`)
}

function buildOptions (m, spec) {
  if (spec === undefined) return undefined
  if (spec && typeof spec === 'object' && spec.$legacyFormatter) return customFormatterFn(m, spec.$legacyFormatter)
  const options = {}
  for (const [key, value] of Object.entries(spec)) {
    if (key === 'getEffectDef') options.getEffectDef = effectDefCallback(m, value)
    else if (key === 'customFormatter') options.customFormatter = customFormatterFn(m, value)
    else if (key === 'enums') options.enums = enumsValue(m, value)
    else options[key] = value
  }
  return options
}

